export type StringsKey = keyof (typeof STRINGS)["en"];

const LangContext = createContext<Lang>("en");

export const LangProvider = LangContext.Provider;

export function useLang(): Lang {
  return useContext(LangContext);
}

/** Theme + language state, owned by the outer App so the whole tree
 *  (including components rendered above the language provider) can read
 *  and change it. */
export type Prefs = {
  theme: Theme;
  lang: Lang;
  setTheme: (theme: Theme) => void;
  setLang: (lang: Lang) => void;
};

const PrefsContext = createContext<Prefs>({
  theme: "dark",
  lang: "en",
  setTheme: () => undefined,
  setLang: () => undefined,
});

export const PrefsProvider = PrefsContext.Provider;

export function usePrefs(): Prefs {
  return useContext(PrefsContext);
}

/** Translate a key, replacing `{name}` placeholders from `vars`.
 *  Missing keys fall back to the English string, then to the key. */
export function translate(lang: Lang, key: string, vars?: Record<string, string | number>): string {
  const dict = STRINGS[lang] ?? STRINGS.en;
  let s = dict[key] ?? STRINGS.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.split(`{${k}}`).join(String(v));
    }
  }
  return s;
}

/** Hook version: returns a `t(key, vars)` bound to the current language. */
export function useT(): (key: string, vars?: Record<string, string | number>) => string {
  const lang = useLang();
  return (key: string, vars?: Record<string, string | number>) => translate(lang, key, vars);
}
