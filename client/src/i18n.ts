// Phase 5 — bilingual UI (English + Roman Urdu) and theme preferences.
//
// Roman Urdu, not Devanagari: the user reads Roman Urdu. Video titles
// and metadata from Jimeng are content, not UI, so they are never
// translated. The Admin Panel stays in English (it is the site owner's
// own tool). Long-form content pages (What is Jimeng?, How to Use, FAQ
// answers, Terms / Copyright / Disclaimer / Privacy / About prose) are
// content too — their page titles are translated, their body text stays
// in English for now.
//
// Preferences: localStorage is the first-paint source (index.html reads
// it before CSS renders, so the page never flashes the wrong theme).
// Logged-in customers also keep theme + language on their account
// (user_settings.theme / .language); the account value is applied once
// it loads, exactly like the download quality/mode preference.

import { createContext, useContext } from "react";

export type Theme = "dark" | "light";
export type Lang = "en" | "ur";

export const THEME_KEY = "jimeng_theme";
export const LANG_KEY = "jimeng_lang";

export function getLocalTheme(): Theme {
  try {
    return localStorage.getItem(THEME_KEY) === "light" ? "light" : "dark";
  } catch {
    return "dark";
  }
}

export function setLocalTheme(theme: Theme): void {
  try {
    localStorage.setItem(THEME_KEY, theme);
  } catch {
    /* storage blocked — the preference just doesn't stick */
  }
}

export function applyTheme(theme: Theme): void {
  try {
    document.documentElement.setAttribute("data-theme", theme);
  } catch {
    /* server render — nothing to apply */
  }
}

export function getLocalLang(): Lang {
  try {
    return localStorage.getItem(LANG_KEY) === "ur" ? "ur" : "en";
  } catch {
    return "en";
  }
}

export function setLocalLang(lang: Lang): void {
  try {
    localStorage.setItem(LANG_KEY, lang);
  } catch {
    /* storage blocked — the preference just doesn't stick */
  }
}

